#!/usr/bin/env python3
"""Generate fixed model descriptors and shared scratch; no weight conversion."""
import json
import math
from pathlib import Path
from weight_schema import schema
ROOT=Path(__file__).resolve().parents[1]
def main():
 c=json.loads((ROOT/'docs/config.json').read_text());h=c['hidden_size'];d=c['head_dim'];qh=c['num_attention_heads'];kh=c['num_key_value_heads'];inter=c['intermediate_size'];n=c['num_hidden_layers'];v=c['vocab_size'];context=c['max_position_embeddings'];width=kh*d
 slots={name:i for i,(name,_) in enumerate(schema())};patches=[];bss={};arena_patches=[]
 lines=['// Generated by tools/model_layout.py.','.data','.p2align 3']
 def record(name,items):
  converted=[]
  for off,item in enumerate(items):
   if isinstance(item,str) and item in bss:
    arena_patches.append((name,off*8,item));converted.append(0)
   else:converted.append(item)
  lines.append(name+': .quad '+','.join(map(str,converted)))
 def weight(record_name,offset,name):
  patches.append((record_name,offset,slots[name]))
 def buffer(name,count):bss[name]=count*4
 for name,count in [('state',h),('normalized',h),('branch',h),('qkvout',(qh+2*kh)*d),('attention',qh*d),('mlpscratch',2*inter),('scores',context),('cos',d//2),('sin',d//2),('logits',v)]:buffer('Lwork_'+name,count)
 for i in range(n):
  prefix=f'model.layers.layers.{i}.';full=(i+1)%c['sliding_window_pattern']==0;cap=context if full else c['window_size']+1;freq='_plamo_rope_global' if full else '_plamo_rope_local'
  q=f'Lq{i}';cache=f'Lc{i}';rot=f'Lr{i}';g=f'Lg{i}';mix=f'Lm{i}';mlp=f'Lp{i}';layer=f'Ll{i}'
  buffer(f'Lkeys{i}',cap*width);buffer(f'Lvalues{i}',cap*width);buffer(f'Lrotated{i}',cap*width)
  record(q,['Lwork_normalized',0,0,0,'Lwork_qkvout',h,qh,kh,d])
  for off,key in [(8,'mixer.qkv_proj.weight'),(16,'mixer.q_norm.weight'),(24,'mixer.k_norm.weight')]:weight(q,off,prefix+key)
  record(cache,[f'Lkeys{i}',f'Lvalues{i}',cap,0,width,int(not full)])
  record(rot,[cache,f'Lrotated{i}',freq,'Lwork_cos','Lwork_sin',kh,d,0,0])
  record(g,['Lwork_qkvout',f'Lrotated{i}',f'Lvalues{i}','Lwork_attention','Lwork_scores',0,d,qh,kh])
  record(mix,[q,cache,rot,g,0,'Lwork_branch',h]);weight(mix,32,prefix+'mixer.o_proj.weight')
  record(mlp,['Lwork_state',0,0,0,0,'Lwork_normalized','Lwork_branch','Lwork_mlpscratch',h,inter])
  for off,key in [(8,'pre_mlp_norm.weight'),(16,'post_mlp_norm.weight'),(24,'mlp.gate_up_proj.weight'),(32,'mlp.down_proj.weight')]:weight(mlp,off,prefix+key)
  record(layer,['Lwork_state',0,0,'Lwork_normalized','Lwork_branch',mix,mlp,h])
  for off,key in [(8,'pre_mixer_norm.weight'),(16,'post_mixer_norm.weight')]:weight(layer,off,prefix+key)
 record('Llayers',[f'Ll{i}' for i in range(n)])
 lines+=['Lscales: .float '+','.join(str(1+0.1*math.log(256) if (i+1)%8==0 else 1.0) for i in range(n)),'.p2align 3','.globl _plamo_model']
 record('_plamo_model',[0,v,h,'Lwork_state','Llayers',n,'Lscales',0,'Lwork_normalized',0,'Lwork_logits'])
 for off,key in [(0,'model.embed_tokens.weight'),(56,'model.norm.weight'),(72,'lm_head.weight')]:weight('_plamo_model',off,key)
 lines+=['.globl _plamo_model_patches','_plamo_model_patches:']
 for rec,off,slot in patches:lines.append(f'.quad {rec}+{off},_plamo_weights+{slot*8}')
 lines+=['.quad 0,0']
 offsets={};total=0
 for name,size in bss.items():
  total=(total+15)//16*16;offsets[name]=total;total+=size
 lines+=['.globl _plamo_arena_size','_plamo_arena_size: .quad '+str(total),'.globl _plamo_arena_patches','_plamo_arena_patches:']
 for rec,off,name in arena_patches:lines.append(f'.quad {rec}+{off},{offsets[name]}')
 lines+=['.quad 0,0']
 (ROOT/'src/model_layout.s').write_text('\n'.join(lines)+'\n')
if __name__=='__main__':main()
