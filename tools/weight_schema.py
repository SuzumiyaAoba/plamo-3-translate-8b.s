#!/usr/bin/env python3
"""Generate model weight names/shapes, never checkpoint data or offsets."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def schema():
 c=json.loads((ROOT/'docs/config.json').read_text());h=c['hidden_size'];d=c['head_dim'];i=c['intermediate_size'];v=c['vocab_size']
 rows=[('model.embed_tokens.weight',[v,h]),('model.norm.weight',[h]),('lm_head.weight',[v,h])]
 for layer in range(c['num_hidden_layers']):
  p=f'model.layers.layers.{layer}.'
  shapes={'mixer.qkv_proj.weight':[(c['num_attention_heads']+2*c['num_key_value_heads'])*d,h], 'mixer.o_proj.weight':[h,h], 'mixer.q_norm.weight':[d], 'mixer.k_norm.weight':[d], 'mlp.gate_up_proj.weight':[2*i,h], 'mlp.down_proj.weight':[h,i], 'pre_mixer_norm.weight':[h], 'post_mixer_norm.weight':[h], 'pre_mlp_norm.weight':[h], 'post_mlp_norm.weight':[h]}
  rows.extend((p+name,shape) for name,shape in shapes.items())
 return rows

def main():
 rows=schema();s=['// Generated by tools/weight_schema.py; original BF16 tensors remain unchanged.','.data','.p2align 3','.globl _plamo_weight_schema','_plamo_weight_schema:']
 for n,(_,shape) in enumerate(rows):s.append(f'.quad Lweightname{n},{len(shape)},Lweightdims{n},_plamo_weights+{n*8}')
 s+=['.quad 0,0,0,0','.section __TEXT,__const']
 for n,(name,shape) in enumerate(rows):s += [f'Lweightname{n}: .asciz "{name}"','.p2align 3',f'Lweightdims{n}: .quad '+','.join(map(str,shape))]
 s+=['.globl _plamo_weights',f'.zerofill __DATA,__bss,_plamo_weights,{len(rows)*8},3']
 (ROOT/'src/weight_schema.s').write_text('\n'.join(s)+'\n')
if __name__=='__main__':main()
