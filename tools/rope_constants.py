#!/usr/bin/env python3
"""Emit fixed model RoPE constants; models no weights and requires no checkpoint."""
import json
import math
from pathlib import Path
import struct
ROOT = Path(__file__).resolve().parents[1]
def fp(x):
    return struct.unpack('f',struct.pack('f',x))[0]
def main():
    config=json.loads((ROOT/'docs/config.json').read_text())
    half=config['head_dim']//2
    lines=['// Generated by tools/rope_constants.py from docs/config.json.', '.section __TEXT,__const','.p2align 2']
    for name,key in [('local','sliding_attention'),('global','full_attention')]:
        p=config['rope_parameters'][key];base=p['rope_theta'];values=[]
        for i in range(half):
            freq=fp(base**(i/half))
            extrap=fp(1/freq)
            if p['rope_type']=='yarn':
                low=half*math.log(p['original_max_position_embeddings']/(p['beta_fast']*2*math.pi))/math.log(base)
                high=half*math.log(p['original_max_position_embeddings']/(p['beta_slow']*2*math.pi))/math.log(base)
                # Each intermediate follows upstream FP32 tensor operations.
                ramp=fp(fp(i-fp(low))/fp(high-low))
                mask=fp(1-max(0,min(1,ramp)))
                interp=fp(1/fp(p['factor']*freq))
                extrap=fp(fp(interp*fp(1-mask))+fp(extrap*mask))
            values.append(extrap)
        lines+=['.globl _plamo_rope_'+name, '_plamo_rope_'+name+':','.float '+','.join(map(repr,values))]
        concentration=1 if p['rope_type']=='default' else 1+0.1*math.log(p['factor'])
        lines+=['.globl _plamo_rope_'+name+'_scale','_plamo_rope_'+name+'_scale:','.float '+repr(fp(concentration))]
    (ROOT/'src/rope_constants.s').write_text('\n'.join(lines)+'\n')
if __name__=='__main__':main()
